# Q1. A cinema ticket costs 750 PKR.
#     A customer buys 4 tickets.
#
#     Calculate and print the total cost.

ticket_price = 750
number_of_tickets = 4

total_cost = ticket_price * number_of_tickets

print("Total Cost:", total_cost, "PKR")


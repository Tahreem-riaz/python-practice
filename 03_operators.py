# Q2. A rectangle has a length of 24 cm and a width
#     of 9 cm.
#
#     Calculate and print:
#     - Area
#     - Perimeter

length = 24
width = 9

area = length * width
perimeter = 2 * (length + width)

print("Area:", area, "cm²")
print("Perimeter:", perimeter, "cm")

